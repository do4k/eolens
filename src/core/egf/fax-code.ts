function createFaxCodeArray(array: number[]): FaxCode[] {
  const result: FaxCode[] = [];
  for (let i = 0; i < array.length; i += 3) {
    result.push(new FaxCode(array[i], array[i + 1], array[i + 2]));
  }
  result.sort((a, b) => a.bitLength - b.bitLength);
  return result;
}

FaxCode.WHITE_CODES = createFaxCodeArray(WHITE_CODES);
FaxCode.BLACK_CODES = createFaxCodeArray(BLACK_CODES);
